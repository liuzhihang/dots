import {chromium} from '/Users/liuzhihang/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import {mkdirSync, statSync, writeFileSync} from 'node:fs';
const out='/private/tmp/dots-atlas-v84-dynamic-final-b25';
mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--no-sandbox','--disable-dev-shm-usage']});
const context=await browser.newContext({acceptDownloads:true,viewport:{width:1920,height:872},deviceScaleFactor:1,reducedMotion:'reduce'});
const page=await context.newPage();
const errors=[],badResponses=[];
page.on('pageerror',error=>errors.push({kind:'pageerror',message:error.message}));
page.on('console',message=>{if(message.type()==='error')errors.push({kind:'console',message:message.text()});});
page.on('response',response=>{if(response.status()>=400)badResponses.push({status:response.status(),url:response.url()});});
async function freezeVisualState(){
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.addStyleTag({content:'*,*::before,*::after{animation:none!important;transition:none!important;scroll-behavior:auto!important}'});
  await page.evaluate(()=>window.scrollTo(0,0));
}
const response=await page.goto('http://127.0.0.1:5173/qa/composition-atlas.html?v=84&captureMethod=playwright-local-chrome',{waitUntil:'domcontentloaded',timeout:30000});
if(!response||response.status()>=400)throw new Error(`atlas navigation failed: ${response?.status()}`);
await page.waitForFunction(()=>document.querySelector('#look-count')?.textContent==='15'&&document.querySelector('#case-count')?.textContent==='66',{timeout:30000});
await page.locator('#atlas-grid [data-detail]').first().waitFor({state:'visible',timeout:30000});
await freezeVisualState();
const atlasTemplate={title:await page.title(),lookCount:await page.locator('#look-count').innerText(),stateCount:await page.locator('#state-count').innerText(),outputCount:await page.locator('#case-count').innerText(),initialStatus:await page.locator('#status').innerText()};
await page.screenshot({path:`${out}/atlas-template-first-page.png`,fullPage:true,animations:'disabled'});
const templateDownloadPromise=page.waitForEvent('download',{timeout:600000});
await page.locator('#capture-all').click();
const templateDownload=await templateDownloadPromise;
const templateBundle=`${out}/template-capture.tar.gz`;
await templateDownload.saveAs(templateBundle);
await page.waitForFunction(()=>document.querySelector('#status')?.textContent.startsWith('捕获完成：'),{timeout:120000});
const templateStatus=await page.locator('#status').innerText();
const templateBytes=statSync(templateBundle).size;
await page.locator('#collection-modular').click();
await page.waitForFunction(()=>Number(document.querySelector('#case-count')?.textContent)>0,{timeout:30000});
const moduleTotal=Number(await page.locator('#case-count').innerText());
const recipeCount=Number(await page.locator('#state-count').innerText());
const assetOptions=await page.locator('#asset-filter option').evaluateAll(options=>options.map(option=>({value:option.value,label:option.textContent})));
if(!assetOptions.some(option=>option.value==='pilot-knit-scarf-v1'))throw new Error('scarf asset is absent from modular filter options');
await page.locator('#asset-filter').selectOption('pilot-knit-scarf-v1');
await page.waitForFunction(()=>document.querySelectorAll('#atlas-grid [data-detail]').length===3,{timeout:30000});
const scarfCards=await page.locator('#atlas-grid [data-detail]').evaluateAll(nodes=>nodes.map(node=>({id:node.getAttribute('data-detail'),text:node.closest('.case-card')?.innerText??''})));
if(scarfCards.length!==3)throw new Error(`expected 3 scarf background cards, got ${scarfCards.length}`);
await page.locator('#atlas-grid [data-detail]').first().click();
await page.locator('#detail').waitFor({state:'visible'});
await page.locator('#detail-preview canvas').waitFor({state:'visible',timeout:30000});
const scarfDetailTitle=await page.locator('#detail-title').innerText();
const scarfRenderMetadata=JSON.parse(await page.locator('#detail-meta pre').innerText());
await page.screenshot({path:`${out}/scarf-coordination-before-edit.png`,fullPage:true,animations:'disabled'});
const scarfNote='实际Canvas复核：围巾外缘可见浅青绿色柔光晕/外溢，与柴犬毛面接触边界不够干净；仅记录该精确围巾×柴犬配方版本，待素材修正后重新检查。';
await page.locator('[data-coordination-status="materialLighting"]').selectOption('issue');
await page.locator('[data-coordination-note="materialLighting"]').fill(scarfNote);
await page.locator('#issue-options input[value="风格"]').check();
await page.locator('#issue-note').fill(scarfNote);
await page.locator('#save-issue').click();
await page.locator('#save-coordination-review').click();
await page.waitForFunction(()=>document.querySelector('#status')?.textContent.includes('已保存精确适配协调性状态'),{timeout:10000});
const scarfSaved=await page.evaluate(()=>({coordination:Object.entries(localStorage).filter(([key])=>key.startsWith('dot-studio-atlas-coordination:')).map(([key,value])=>({key,value:JSON.parse(value)})),issues:Object.entries(localStorage).filter(([key])=>key.startsWith('dot-studio-atlas-issues:')).map(([key,value])=>({key,value:JSON.parse(value)}))}));
const scarfReview=scarfSaved.coordination.find(entry=>entry.value.subject?.recipeId?.includes('pilot-knit-scarf-v1'));
if(!scarfReview)throw new Error('saved scarf coordination record was not found by exact recipe subject');
if(scarfReview.value.checklist.materialLighting!=='issue'||scarfReview.value.disposition!=='pending')throw new Error('scarf coordination issue was not retained as pending');
if(['proportion','contact','occlusion','palette'].some(key=>scarfReview.value.checklist[key]!=='unreviewed'))throw new Error('unreviewed scarf checklist items were changed');
if(scarfSaved.coordination.length!==1)throw new Error(`isolated browser profile should contain exactly one coordination record, got ${scarfSaved.coordination.length}`);
if(scarfSaved.issues.length!==1)throw new Error(`isolated browser profile should contain exactly one issue annotation, got ${scarfSaved.issues.length}`);
await page.screenshot({path:`${out}/scarf-coordination-after-edit.png`,fullPage:true,animations:'disabled'});
await page.locator('#close-detail').click();
await page.locator('#asset-filter').selectOption('');
await page.waitForFunction(total=>Number(document.querySelector('#case-count')?.textContent)===total,moduleTotal,{timeout:30000});
await page.screenshot({path:`${out}/atlas-modular-first-page.png`,fullPage:true,animations:'disabled'});
const moduleDownloadPromise=page.waitForEvent('download',{timeout:600000});
await page.locator('#capture-modules').click();
const moduleDownload=await moduleDownloadPromise;
const moduleBundle=`${out}/module-capture.tar.gz`;
await moduleDownload.saveAs(moduleBundle);
await page.waitForFunction(()=>document.querySelector('#status')?.textContent.startsWith('模块捕获完成：'),{timeout:120000});
const moduleStatus=await page.locator('#status').innerText();
const moduleBytes=statSync(moduleBundle).size;
const final={captureMethod:'playwright-local-chrome',userAgent:await page.evaluate(()=>navigator.userAgent),viewport:{width:1920,height:872},atlasTemplate,templateBundle,templateBytes,templateStatus,modules:{assetOptions,recipeCount,moduleTotal,scarfCards,scarfDetailTitle,scarfRenderMetadata,scarfReview:scarfReview.value,scarfIssueAnnotation:scarfSaved.issues[0].value,moduleBundle,moduleBytes,moduleStatus},errors,badResponses};
writeFileSync(`${out}/browser-result.json`,JSON.stringify(final,null,2));
console.log(JSON.stringify(final,null,2));
await browser.close();
